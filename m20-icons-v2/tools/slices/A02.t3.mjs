/**
 * Tranche 1's polygon reader, with the two things this tranche's files need added:
 * GROUP TRANSFORMS (Elm's logo is seven polygons inside a `scale(1,-1)` group,
 * each with its own translate/rotate) and a `<style>` CLASS TABLE (EJS paints its
 * polygons through `.cls-1` / `.cls-2`). Re-emitting a polygon's points as
 * `M x y L x y … Z` and baking its transform into the numbers is a FORMAT
 * conversion, not a redraw — the same move spec-engine.mjs already makes for
 * `<circle>` and tranche 1 makes for SAP's `<polyline>`. Kept local on purpose:
 * the engine is shared with the frozen sets.
 */
const polyShapes = (file) => {
	const raw = readFileSync(join(SRCDIR, file), 'utf8');
	const classes = {};
	for (const c of raw.matchAll(/\.([A-Za-z][\w-]*)\s*\{\s*fill\s*:\s*(#[0-9a-fA-F]{3,8})\s*;?\s*\}/g)) {
		classes[c[1]] = c[2].toUpperCase();
	}
	const out = [];
	const stack = [];
	for (const m of raw.matchAll(/<(\/?)(g|polygon|polyline|svg)\b([^>]*)>/g)) {
		const [, closing, name, attrs] = m;
		if (name === 'svg') { continue; }
		if (closing) { if (name === 'g') { stack.pop(); } continue; }
		const tf = (attrs.match(/\stransform="([^"]+)"/) || [])[1] || null;
		if (name === 'g') { stack.push(tf); continue; }
		const pts = ((attrs.match(/\spoints="([^"]+)"/) || [])[1] || '').trim().split(/[\s,]+/).map(Number);
		const cls = (attrs.match(/\sclass="([^"]+)"/) || [])[1];
		const fill = (attrs.match(/\sfill="(#[0-9a-fA-F]{3,8})"/) || [])[1]
			|| (attrs.match(/fill:\s*(#[0-9a-fA-F]{3,8})/) || [])[1]
			|| (cls && classes[cls]) || null;
		let d = '';
		for (let i = 0; i < pts.length; i += 2) { d += `${i ? 'L' : 'M'}${pts[i]} ${pts[i + 1]}`; }
		let p = svgpath(`${d}Z`);
		const chain = [...stack, tf];
		for (let i = chain.length - 1; i >= 0; i--) { if (chain[i]) { p = p.transform(chain[i]); } }
		out.push({ d: round(p.abs().toString()), fill: fill ? fill.toUpperCase() : null });
	}
	return out;
};

/**
 * De Casteljau: split every cubic in a path in four. The CURVE IS UNCHANGED — a
 * split is exact — but the control polygon collapses onto it, and that is what the
 * fit needs. pathkit's bbox is a control-point hull, and EJS's swoosh is one cubic
 * whose control point sits 6.7 units OUTSIDE the artboard: the raw hull measures
 * 14.26 x 6.45 where the drawn curve is 7.55 x 6.45, so the fit scaled the mark to
 * 53% of its envelope and pushed it off-centre. Local, because this is a property
 * of one source file and not of the engine (which the frozen sets share).
 */
const splitCubics = (d, times = 2) => {
	const lerp = (a, b, t) => [a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t];
	const halve = (p0, p1, p2, p3) => {
		const a = lerp(p0, p1, 0.5), b = lerp(p1, p2, 0.5), c = lerp(p2, p3, 0.5);
		const ab = lerp(a, b, 0.5), bc = lerp(b, c, 0.5), m = lerp(ab, bc, 0.5);
		return [[p0, a, ab, m], [m, bc, c, p3]];
	};
	let out = '';
	svgpath(d).abs().unarc().unshort().iterate((seg, _i, x, y) => {
		if (seg[0] === 'C') {
			let runs = [[[x, y], [seg[1], seg[2]], [seg[3], seg[4]], [seg[5], seg[6]]]];
			for (let n = 0; n < times; n++) { runs = runs.flatMap(r => halve(...r)); }
			for (const r of runs) { out += `C${r[1].join(' ')} ${r[2].join(' ')} ${r[3].join(' ')}`; }
		} else if (seg[0] === 'H') { out += `L${seg[1]} ${y}`; }
		else if (seg[0] === 'V') { out += `L${x} ${seg[1]}`; }
		else { out += seg[0] + seg.slice(1).join(' '); }
	});
	return round(out);
};

